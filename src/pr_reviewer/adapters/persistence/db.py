"""PostgreSQL persistence for review history.

Same public functions as the old SQLite version (init_db, save_review,
list_reviews, get_review, get_stats), so the worker and the dashboard
routes did not need to change.

Configuration: DATABASE_URL, e.g.
    postgresql://pr_reviewer:secret@postgres:5432/pr_reviewer

A small connection pool is created lazily on first use and shared by all
threads, so it works for both the API process and the worker process.
"""
from __future__ import annotations

import os
import threading
from datetime import datetime
from typing import Any
from urllib.parse import urlparse

from psycopg.rows import dict_row
from psycopg.types.json import Jsonb
from psycopg_pool import ConnectionPool

from src.pr_reviewer.domain.contracts import Finding

_pool: ConnectionPool | None = None
_pool_lock = threading.Lock()

# Arbitrary constant: makes concurrent init_db() calls (api + worker starting
# together) run one after the other instead of racing on CREATE TABLE.
_SCHEMA_LOCK_ID = 727_274_001


def database_url() -> str:
    url = os.getenv("DATABASE_URL")
    if not url:
        raise RuntimeError(
            "DATABASE_URL is not set. Example: "
            "postgresql://user:password@localhost:5432/pr_reviewer"
        )
    return url


def db_info() -> str:
    """Safe-to-display description of the database (never includes the password)."""
    u = urlparse(database_url())
    return f"postgresql://{u.hostname}:{u.port or 5432}{u.path}"


def _get_pool() -> ConnectionPool:
    global _pool
    if _pool is None:
        with _pool_lock:
            if _pool is None:
                _pool = ConnectionPool(
                    conninfo=database_url(),
                    min_size=1,
                    max_size=int(os.getenv("DB_POOL_MAX", "10")),
                    kwargs={"row_factory": dict_row},
                    open=True,
                    # wait for Postgres to come up instead of failing instantly at boot
                    timeout=30,
                )
    return _pool


def close_pool() -> None:
    global _pool
    if _pool is not None:
        _pool.close()
        _pool = None


def _conn():
    """`with _conn() as conn:` -> one transaction, committed on success,
    rolled back if the block raises."""
    return _get_pool().connection()


def init_db() -> None:
    with _conn() as conn:
        conn.execute("SELECT pg_advisory_xact_lock(%s)", (_SCHEMA_LOCK_ID,))
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS reviews (
                id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                repo                TEXT NOT NULL,
                pr_number           INTEGER NOT NULL,
                pr_title            TEXT,
                head_sha            TEXT,
                verdict             TEXT,            -- hold | comment | approve | request_changes
                summary             TEXT,
                overall_confidence  DOUBLE PRECISION,
                needs_human_review  BOOLEAN NOT NULL DEFAULT FALSE,
                graph_context       JSONB,
                created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
                UNIQUE (repo, pr_number, head_sha)
            )
            """
        )
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS findings (
                id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                review_id   BIGINT NOT NULL REFERENCES reviews(id) ON DELETE CASCADE,
                agent_type  TEXT NOT NULL,
                severity    TEXT NOT NULL,
                category    TEXT,
                summary     TEXT NOT NULL,
                file        TEXT,
                line        INTEGER,
                confidence  DOUBLE PRECISION,
                rationale   TEXT,
                suggestion  TEXT,
                created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
            )
            """
        )
        conn.execute("CREATE INDEX IF NOT EXISTS idx_reviews_repo ON reviews(repo)")
        conn.execute("CREATE INDEX IF NOT EXISTS idx_reviews_time ON reviews(created_at DESC)")
        conn.execute("CREATE INDEX IF NOT EXISTS idx_findings_review ON findings(review_id)")


def _as_dict(f: Any) -> dict[str, Any]:
    """The worker hands us plain dicts (Review.findings); older callers pass
    Finding models. Normalise both, and turn enums into plain strings."""
    d = dict(f) if isinstance(f, dict) else f.model_dump()
    for k in ("agent_type", "severity"):
        d[k] = getattr(d[k], "value", d[k])
    return d


def _jsonable(row: dict[str, Any]) -> dict[str, Any]:
    """Keep the REST API output identical to the SQLite version:
    timestamps as ISO-8601 strings."""
    for k, v in row.items():
        if isinstance(v, datetime):
            row[k] = v.isoformat()
    return row


def save_review(
    repo: str,
    pr_number: int,
    pr_title: str,
    head_sha: str,
    verdict: str,
    summary: str,
    overall_confidence: float,
    needs_human_review: bool,
    findings: list[Finding],
    graph_context: dict | None = None,
) -> int:
    """Insert or update the review for (repo, PR, head_sha) and replace its
    findings, all in ONE transaction."""
    with _conn() as conn:
        row = conn.execute(
            """
            INSERT INTO reviews (repo, pr_number, pr_title, head_sha, verdict,
                                 summary, overall_confidence, needs_human_review,
                                 graph_context, created_at)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, now())
            ON CONFLICT (repo, pr_number, head_sha) DO UPDATE SET
                pr_title           = EXCLUDED.pr_title,
                verdict            = EXCLUDED.verdict,
                summary            = EXCLUDED.summary,
                overall_confidence = EXCLUDED.overall_confidence,
                needs_human_review = EXCLUDED.needs_human_review,
                graph_context      = EXCLUDED.graph_context,
                created_at         = EXCLUDED.created_at
            RETURNING id
            """,
            (repo, pr_number, pr_title, head_sha, verdict, summary,
             overall_confidence, bool(needs_human_review),
             Jsonb(graph_context) if graph_context else None),
        ).fetchone()
        review_id = row["id"]

        conn.execute("DELETE FROM findings WHERE review_id = %s", (review_id,))
        rows = []
        for f in findings:
            f = _as_dict(f)
            rows.append((
                review_id, f["agent_type"], f["severity"], f.get("category"),
                f["summary"], f.get("file"), f.get("line"), f.get("confidence"),
                f.get("rationale"), f.get("suggestion"),
            ))
        if rows:
            with conn.cursor() as cur:
                cur.executemany(
                    """
                    INSERT INTO findings (review_id, agent_type, severity, category,
                                          summary, file, line, confidence, rationale,
                                          suggestion)
                    VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                    """,
                    rows,
                )
        return review_id


def list_reviews(repo: str | None = None, limit: int = 50) -> list[dict[str, Any]]:
    # graph_context is large and only the detail view needs it, so it is not selected here.
    sql = """
        SELECT r.id, r.repo, r.pr_number, r.pr_title, r.head_sha, r.verdict,
               r.summary, r.overall_confidence, r.needs_human_review, r.created_at,
               COUNT(f.id) AS finding_count,
               COALESCE(string_agg(DISTINCT f.agent_type, ','), '') AS agents
        FROM reviews r LEFT JOIN findings f ON f.review_id = r.id
    """
    params: list[Any] = []
    if repo:
        sql += " WHERE r.repo = %s"
        params.append(repo)
    sql += " GROUP BY r.id ORDER BY r.created_at DESC LIMIT %s"
    params.append(limit)

    with _conn() as conn:
        out = []
        for d in conn.execute(sql, params).fetchall():
            d["agents"] = sorted(a for a in d["agents"].split(",") if a)
            out.append(_jsonable(d))
        return out


def get_review(review_id: int) -> dict[str, Any] | None:
    with _conn() as conn:
        review = conn.execute("SELECT * FROM reviews WHERE id = %s", (review_id,)).fetchone()
        if not review:
            return None
        review["findings"] = [
            _jsonable(r) for r in conn.execute(
                "SELECT * FROM findings WHERE review_id = %s ORDER BY id", (review_id,)
            ).fetchall()
        ]
        return _jsonable(review)   # graph_context (JSONB) already comes back as a dict


def get_stats() -> dict[str, Any]:
    with _conn() as conn:
        total = conn.execute("SELECT COUNT(*) AS n FROM reviews").fetchone()["n"]
        by_verdict = {
            r["verdict"]: r["n"]
            for r in conn.execute("SELECT verdict, COUNT(*) AS n FROM reviews GROUP BY verdict")
        }
        by_agent = {
            r["agent_type"]: r["n"]
            for r in conn.execute("SELECT agent_type, COUNT(*) AS n FROM findings GROUP BY agent_type")
        }
        by_severity = {
            r["severity"]: r["n"]
            for r in conn.execute("SELECT severity, COUNT(*) AS n FROM findings GROUP BY severity")
        }
        repos = [
            r["repo"]
            for r in conn.execute("SELECT DISTINCT repo FROM reviews ORDER BY repo")
        ]
    return {
        "total_reviews": total,
        "by_verdict": by_verdict,
        "by_agent": by_agent,
        "by_severity": by_severity,
        "repos": repos,
    }
